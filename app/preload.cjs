const {contextBridge,ipcRenderer}=require('electron');
contextBridge.exposeInMainWorld('hearth',{
  library:()=>ipcRenderer.invoke('get-library'),
  aiEngineStatus:()=>ipcRenderer.invoke('ai-engine-status'),
  aiModelPath:()=>ipcRenderer.invoke('ai-model-path'),
  aiModelDownload:()=>ipcRenderer.invoke('ai-model-download'),
  aiModelCancel:()=>ipcRenderer.invoke('ai-model-cancel'),
  aiBrowse:kind=>ipcRenderer.invoke('ai-browse',kind),
  onAiModelStatus:fn=>ipcRenderer.on('ai-model-status',(_event,data)=>fn(data)),
  aiStart:(id,track,options)=>ipcRenderer.invoke('ai-transcript-start',id,track,options),
  aiPosition:(id,track,time,playing)=>ipcRenderer.invoke('ai-transcript-position',id,track,time,playing),
  aiAutoStart:(id,track,position,options)=>ipcRenderer.invoke('ai-auto-start',id,track,position,options),
  aiAutoPosition:(id,track,position)=>ipcRenderer.invoke('ai-auto-position',id,track,position),
  aiCancel:()=>ipcRenderer.invoke('ai-transcript-cancel'),
  aiStatus:()=>ipcRenderer.invoke('ai-transcript-status'),
  aiGet:(id,track)=>ipcRenderer.invoke('ai-transcript-get',id,track),
  aiSearch:(id,query)=>ipcRenderer.invoke('ai-transcript-search',id,query),
  onAiStatus:fn=>ipcRenderer.on('ai-transcription-status',(_event,data)=>fn(data)),
  updaterStatus:()=>ipcRenderer.invoke('updater-status'),
  checkUpdates:()=>ipcRenderer.invoke('updater-check'),
  downloadUpdate:()=>ipcRenderer.invoke('updater-download'),
  installUpdate:()=>ipcRenderer.invoke('updater-install'),
  onUpdateStatus:fn=>ipcRenderer.on('updater-status-changed',(_event,data)=>fn(data)),
  addFolder:()=>ipcRenderer.invoke('choose-folder'),
  removeFolder:p=>ipcRenderer.invoke('remove-folder',p),
  rescan:()=>ipcRenderer.invoke('rescan'),
  edit:(id,changes)=>ipcRenderer.invoke('update-book',id,changes),
  cover:id=>ipcRenderer.invoke('choose-cover',id),
  progress:(id,p)=>ipcRenderer.invoke('save-progress',id,p),
  property:(type,id,value)=>ipcRenderer.invoke('set-property',type,id,value),
  profile:name=>ipcRenderer.invoke('profile',name),
  settings:values=>ipcRenderer.invoke('settings',values),
  backup:()=>ipcRenderer.invoke('backup'),
  restore:()=>ipcRenderer.invoke('restore'),
  onChanged:fn=>ipcRenderer.on('library-changed',fn),
  onScanProgress:fn=>ipcRenderer.on('scan-progress',(_event,data)=>fn(data))
});
